"""Regenerate MCU gzip from the reviewed UTF-8 web_ui.h (deterministic mtime)."""
from pathlib import Path
import gzip,hashlib,re
root=Path(__file__).resolve().parents[1]
fw=root/'firmware/IncubatorController'
def main():
    source=(fw/'web_ui.h').read_text(encoding='utf8')
    m=re.search(r'R"HTML\((.*?)\)HTML"',source,re.S)
    if not m:raise SystemExit('WEB_UI raw string not found')
    data=m[1].encode('utf8');compressed=gzip.compress(data,compresslevel=9,mtime=0)
    lines=['#pragma once','#include <Arduino.h>','// Generated by tools/generate_web_assets.py; do not hand-edit.',f'// UTF-8 bytes={len(data)} sha256={hashlib.sha256(data).hexdigest()}','const uint8_t WEB_UI_GZIP[] PROGMEM={']
    lines+=[' '+','.join(f'0x{n:02x}' for n in compressed[i:i+16])+',' for i in range(0,len(compressed),16)]
    (fw/'web_ui_gzip.h').write_text('\n'.join(lines+['};','']),encoding='utf8',newline='\n')
    print(f'Gzip generated: {len(data)} -> {len(compressed)} bytes')
if __name__=='__main__':main()
